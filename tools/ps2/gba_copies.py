#!/usr/bin/env python3
"""Writes build/ps2/gba_copies.c: the GBA address of every global-state copy (NAME__base in the PS2 link), sorted.
Code still kept as bytes in the asm (data pools, jump tables) holds GBA ROM addresses the PS2 relocation can't see;
glue/arm_ports.c's find_entry maps such an address to the same offset in the copy (ps2_gba_copy).
  gba_copies.py OUT.c ARM_ELF src/auto/*_gstate_ps2.c"""
import re, subprocess, sys

out, elf, srcs = sys.argv[1], sys.argv[2], sys.argv[3:]
names = set()
for f in srcs:
    names |= set(re.findall(r"^extern const u\d+ (\w+)__base\[\];", open(f).read(), re.M))
addr = {}
for line in subprocess.run(["arm-none-eabi-nm", elf], capture_output=True, text=True, check=True).stdout.split("\n"):
    p = line.split()
    if len(p) == 3 and p[2] in names and p[1] in "Tt":
        addr[p[2]] = int(p[0], 16) & ~1
rows = sorted((a, n) for n, a in addr.items())
missing = sorted(names - set(addr))
lines = ["// generated by tools/ps2/gba_copies.py: global-state copies by GBA address (%d; %d not in the ROM's symbols)"
         % (len(rows), len(missing))]
lines += ["extern const unsigned char %s__base[];" % n for a, n in rows]
lines += ["const struct { unsigned gba; const unsigned char *ps2; } ps2_gba_copies[] = {"]
lines += ["    { 0x%08X, %s__base }," % (a, n) for a, n in rows]
lines += ["};", "const int ps2_gba_ncopies = %d;" % len(rows)]
open(out, "w").write("\n".join(lines) + "\n")
